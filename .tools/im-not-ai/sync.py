"""im-not-ai의 검사 파일과 글쓰기 규칙을 새 버전으로 갱신한다.

사용: python .tools/im-not-ai/sync.py <레포 클론> [--apply] [--commit 해시]
기본은 임시 폴더에서 시험만 하고 바뀐 내용을 보고한다. --apply를 붙이면 프로젝트에 쓴다.
규칙 파일은 지침으로 로드되므로, 적용 전에 보고된 규칙 변경을 사람이 읽는다.
"""
import argparse
import difflib
import importlib.util
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
VENDOR = HERE / "upstream"
RULE = HERE.parents[1] / ".claude" / "rules" / "korean-humanize.md"
VERSIONS = HERE.parents[1] / "versions.toml"
FILES = [
    "LICENSE",
    "scripts/prepare_monolith_input.py",
    "scripts/console.py",
    "skills/humanize-korean/references/metrics.py",
    "skills/humanize-korean/references/metrics_v2.py",
    "skills/humanize-korean/references/baseline.json",
    "skills/humanize-korean/references/baseline_v2.json",
]
QUICK_RULES = "skills/humanize-korean/references/quick-rules.md"
DROP = ("C-2", "C-5", "C-9", "C-10", "J-1")  # 레슨에 필요한 목록·번호·표를 없애는 규칙
PROTECT = ("**Do-NOT", "**서법 보존", "**내용 앵커")
# 검사 도구는 네트워크와 프로세스 실행이 필요 없다. 이런 호출이 생기면 사람이 먼저 본다
FORBIDDEN = re.compile(r"\b(socket|subprocess|urllib|requests|http\.client|ftplib)\b"
                       r"|\b(eval|exec|os\.system|os\.popen)\(")
SAMPLE = ("이것이 원리를 이해해야 하는 이유다. 중요한 것은 컨트롤러가 호출된다는 점이다. "
          "향후 개발자는 역량을 강화해야 한다. 요약하면 검증은 매우 중요하다.")
HEADER = """---
paths:
  - "lecture/**"
---

# Korean prose rules

Apply these while drafting Korean lesson text, reference pages, and chat replies in lecture sessions. They are drafting rules: never run them as a rewrite pass over a finished lesson.

Source: `skills/humanize-korean/references/quick-rules.md` of https://github.com/epoko77-ai/im-not-ai, commit {commit}. Layout rules {dropped}, and the self-check and grading sections are removed: lessons need lists, numbered steps, and tables, and those parts depend on the repo's scripts. Regenerate with `.tools/im-not-ai/sync.py`; do not edit this file by hand.

- Leave code blocks, inline `code`, HTML tags and attributes, identifiers, class and annotation names, commands, paths, URLs, and quoted program output unchanged.
- Clarity for the learner outranks these rules. Keep a repeated term, a plain step list, or a short sentence when it makes the mechanism easier to follow.
- Use glossary terms unchanged.
- `[S1]` marks a stronger signal than `[S2]`.

## Protect

"""


def load_check():
    spec = importlib.util.spec_from_file_location("check_korean", HERE / "check-korean.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def build_rule(clone, commit):
    lines = (clone / QUICK_RULES).read_text(encoding="utf-8").split("\n")
    protect = [line for line in lines if line.startswith(PROTECT)]
    if len(protect) != len(PROTECT):
        raise ValueError(f"보호 문단을 {len(PROTECT)}개 찾지 못했다: {len(protect)}개")
    starts = [i for i, line in enumerate(lines) if line.startswith("## ")]
    begin = next((i for i in starts if lines[i].startswith("## A.")), None)
    end = next((i for i in starts if lines[i].startswith("## 자체검증")), None)
    if begin is None or end is None:
        raise ValueError("규칙 본문의 시작(## A.)이나 끝(## 자체검증)을 찾지 못했다")
    prefixes = tuple(f"- **{rule_id}**" for rule_id in DROP)
    body = [line for line in lines[begin:end] if not line.startswith(prefixes)]
    license_text = (clone / "LICENSE").read_text(encoding="utf-8").strip()
    return (HEADER.format(commit=commit, dropped=", ".join(DROP))
            + "\n\n".join(protect) + "\n\n---\n" + "\n".join(body).rstrip()
            + "\n\n## License\n\nThe rules above are adapted from im-not-ai.\n\n"
            + license_text + "\n")


def rule_ids(text):
    return set(re.findall(r"^- \*\*([A-Z]-\d+)\*\*", text, re.M))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("clone", type=pathlib.Path)
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--commit")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    sys.stderr.reconfigure(encoding="utf-8")

    missing = [name for name in FILES + [QUICK_RULES] if not (args.clone / name).exists()]
    if missing:
        sys.exit(f"레포에 없는 파일: {missing}")
    risky = [f"{name}: {match.group(0)}" for name in FILES if name.endswith(".py")
             for match in FORBIDDEN.finditer((args.clone / name).read_text(encoding="utf-8"))]
    if risky:
        sys.exit(f"사람이 먼저 볼 호출: {risky}")
    commit = args.commit or subprocess.run(
        ["git", "-C", str(args.clone), "rev-parse", "--short", "HEAD"],
        capture_output=True, text=True, check=True).stdout.strip()

    try:
        rule = build_rule(args.clone, commit)
    except ValueError as error:
        sys.exit(f"규칙 생성 실패: {error}")
    with tempfile.TemporaryDirectory() as tmp:
        trial = pathlib.Path(tmp) / "vendor"
        for name in FILES:
            target = trial / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(args.clone / name, target)
        try:
            result = load_check().scan(SAMPLE, vendor=trial)
        except Exception as error:
            sys.exit(f"검사 시험 실패: {error}")
    if not result["tells"]:
        sys.exit("검사 시험 실패: 표본에서 패턴을 찾지 못했다")

    changed = [name for name in FILES if not (VENDOR / name).exists()
               or (VENDOR / name).read_bytes() != (args.clone / name).read_bytes()]
    old_rule = RULE.read_text(encoding="utf-8") if RULE.exists() else ""
    print(f"시험 통과: 표본 {result['tells']}건, 커밋 {commit}")
    print(f"바뀐 파일: {changed or '없음'}")
    print(f"추가된 규칙: {sorted(rule_ids(rule) - rule_ids(old_rule)) or '없음'}")
    print(f"사라진 규칙: {sorted(rule_ids(old_rule) - rule_ids(rule)) or '없음'}")
    delta = [line for line in difflib.unified_diff(old_rule.split("\n"), rule.split("\n"), lineterm="", n=0)
             if line[:1] in "+-" and line[:3] not in ("+++", "---")]
    print(f"규칙 파일 변경 {len(delta)}줄")
    print("\n".join(line[:160] for line in delta))
    if not args.apply:
        print("시험만 했다. 위 변경을 읽고 --apply로 적용한다.")
        return
    versions, found = re.subn(r'(?m)^im-not-ai = ".*"$', f'im-not-ai = "{commit}"',
                              VERSIONS.read_text(encoding="utf-8", newline=""))
    if found != 1:
        sys.exit("versions.toml에서 im-not-ai 줄을 찾지 못했다")
    for name in FILES:
        target = VENDOR / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(args.clone / name, target)
    VERSIONS.write_text(versions, encoding="utf-8", newline="")
    RULE.parent.mkdir(parents=True, exist_ok=True)
    RULE.write_text(rule, encoding="utf-8", newline="\n")
    print("적용했다.")


if __name__ == "__main__":
    main()
